#!/usr/bin/env python3
"""Pack SoleStock into js/solestock-bundle.js for the in-browser demo.

Run this again whenever the SoleStock code changes:

    python tools/build_demo_bundle.py path/to/SoleStock

The bundle holds the project's own source files, unchanged, so the demo
always runs exactly what is on GitHub.
"""

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEFAULT_OUT = HERE.parent / "js" / "solestock-bundle.js"


def read(path):
    return path.read_text(encoding="utf-8")


def build(project):
    package = project / "solestock"
    sample = project / "tests" / "data" / "sample_inventory.txt"
    for needed in (package, sample):
        if not needed.exists():
            sys.exit(f"Cannot find {needed}. "
                     "Pass the SoleStock project folder.")

    files = {f"solestock/{path.name}": read(path)
             for path in sorted(package.glob("*.py"))}
    version = "unknown"
    for line in files.get("solestock/__init__.py", "").splitlines():
        if line.startswith("__version__"):
            version = line.split("=", 1)[1].strip().strip("\"'")

    return {
        "version": version,
        "files": files,
        "sample": read(sample),
        "runner": read(HERE / "session_runner.py"),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("project", type=Path, help="the SoleStock folder")
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()

    bundle = build(args.project.resolve())
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(
        "/* Generated by tools/build_demo_bundle.py. Do not edit by hand. */\n"
        "window.SOLESTOCK_DEMO = "
        + json.dumps(bundle, indent=1, ensure_ascii=True) + ";\n",
        encoding="utf-8",
    )
    print(f"Wrote {args.out} ({len(bundle['files'])} source files, "
          f"SoleStock {bundle['version']})")


if __name__ == "__main__":
    main()
